// ─── HELPERS ──────────────────────────────────────────────────────────────────

// Flatten all foods into a single searchable array
const ALL_FOODS_V3 = Object.values(FOOD_DB_V3).reduce(function(acc, arr) {
  return acc.concat(arr);
}, []);

// Filter by mealType
function getFoodsByMealType(mealType) {
  return ALL_FOODS_V3.filter(function(f) {
    return f.mealType.indexOf(mealType) >= 0;
  });
}

// Filter by tags (allergies/exclusions)
function filterFoodsForUser(foods, excludeTags) {
  if (!excludeTags || !excludeTags.length) return foods;
  return foods.filter(function(f) {
    return !f.tags.some(function(t) { return excludeTags.indexOf(t) >= 0; });
  });
}

// Filter by prepTime
function filterByPrepTime(foods, maxMinutes) {
  if (!maxMinutes) return foods;
  return foods.filter(function(f) { return (f.prepTime || 99) <= maxMinutes; });
}

// Filter by proteinSource variety (avoid >2 consecutive same source)
function filterByProteinRotation(foods, usedSources, maxConsecutive) {
  maxConsecutive = maxConsecutive || 2;
  return foods.filter(function(f) {
    if (!f.proteinSource) return true;
    var count = 0;
    for (var i = usedSources.length - 1; i >= 0; i--) {
      if (usedSources[i] === f.proteinSource) count++;
      else break;
    }
    return count < maxConsecutive;
  });
}

// Get complete meals for lunch/dinner (both mealTypes combined, no duplicates)
function getLunchDinnerMeals() {
  var seen = {};
  var result = [];
  ALL_FOODS_V3.forEach(function(f) {
    if ((f.mealType.indexOf('lunch') >= 0 || f.mealType.indexOf('dinner') >= 0) && !seen[f.id]) {
      seen[f.id] = true;
      result.push(f);
    }
  });
  return result;
}
